from airtest.core.api import *

using("../utility/biz_utils.air")

from typing import Callable, Optional, Tuple, Any
from biz_utils import (
    monitor_task_status_v2, image_upload, ImageOcrRemote
)
from LLM import remote_ds_r1_reasoning_copy, parse_model_output_to_json_copy


def llm_call(image_url: str, sys_prompt: str = "", user_prompt: str = "") -> dict:
    """
    Invoke a multimodal large language model (Qwen-VL) to semantically understand an image and return structured results in a specified JSON format.
    This function encapsulates the system prompt, user instruction, and image input,
    and automatically parses the raw model output into a dictionary.

    Args:
        image_url (str): A publicly accessible URL of the image (typically generated by image_upload).
        sys_prompt (str): System role prompt to define the model's behavior. If empty, a default OCR assistant prompt is used.
        user_prompt (str): User instruction guiding how the model should interpret the image content. If empty, a default instruction for extracting server name is used.

    Returns:
        dict: The model response parsed into a dictionary. Example: {"server_name": "East China Zone 1"}.
    """
    if not sys_prompt.strip():
        sys_prompt = (
            "你是一个ocr助手，可以帮助用户精准识别图片中的文字，并按照用户意愿，"
            "将识别出的文字以指定的格式返回。"
        )
    if not user_prompt.strip():
        user_prompt = (
            "请将图片中的服务器名称提取出来，并以json的格式将区服名称整理给我。\n"
            "注意：\n"
            "1. 返回json格式时，不要带有```json```等markdown标记；\n"
            "2. 仅返回如下格式的JSON对象，不要包含任何其他文字：\n"
            '   {"server_name": "区服名称"}\n'
            "3. 严格遵守以上要求。"
        )
    message = [
        {
            "role": "system",
            "content": [{"text": sys_prompt}]
        },
        {
            "role": "user",
            "content": [
                {"image": image_url},  # Image input
                {"text": user_prompt}  # Text instruction
            ]
        }
    ]

    model_res = remote_ds_r1_reasoning_copy(input_content=message, model="qwen-vl-max")
    res_dict = parse_model_output_to_json_copy(model_res)

    return res_dict


def get_server_name_with_ocr_and_llm(
        image: Any,
        user_prompt: str = "",
        ocr_fix_dict: Optional[dict[str, str]] = None,
        llm_fix_dict: Optional[dict[str, str]] = None,
        ocr_func: Optional[Callable] = None,
        ocr_index: Optional[Tuple[int, int]] = None,
        llm_key: str = "server_name",
        validation: bool = True,
        use_ocr_only: bool = False,
        use_llm_only: bool = False
) -> Tuple[str, str]:
    """
    Extract the server name from an image using both OCR and LLM approaches, with optional consistency validation.
    Supports running only OCR or only LLM when explicitly specified.

    Args:
        image (Any): The image object to be processed.
        user_prompt (str): User instruction sent to the LLM to guide extraction of the server name.
                           Custom logic (e.g., different field names) can be controlled via this parameter.
        ocr_fix_dict (Optional[dict[str, str]]): A mapping dictionary to correct common OCR misrecognitions.
                                                 Keys are raw OCR outputs; values are corrected strings.
        llm_fix_dict (Optional[dict[str, str]]): A mapping dictionary to correct common LLM misinterpretations.
                                                 Keys are raw LLM outputs; values are corrected strings.
        ocr_func (Optional[Callable]): A custom post-processing function for raw OCR results.
                                       If provided, this function is called directly on the OCR output;
                                       it takes precedence over ocr_index.
        ocr_index (Optional[Tuple[int, int]]): Specifies the position (row, column) in the 2D OCR result list to extract text,
                                              e.g., (0, 0) means the first row and first column.
                                              Only used if ocr_func is not provided.
        llm_key (str): The key used to extract the server name from the LLM's returned dictionary. Default is "server_name".
        validation (bool): Whether to enable consistency validation between OCR and LLM results.
                           If True and the two results differ, a ValueError is raised.
                           Note: validation is skipped if only one method is used.
        use_ocr_only (bool): If True, only perform OCR recognition and skip LLM. Returns (OCR_result, "").
        use_llm_only (bool): If True, only perform LLM recognition and skip OCR. Returns ("", LLM_result).

    Returns:
        Tuple[str, str]: (Server name from OCR, Server name from LLM). One element may be empty if only one method is used.

    Raises:
        ValueError: If validation=True and both methods are used but their results do not match.
                    Also raised if both use_ocr_only and use_llm_only are True.
    """
    if use_ocr_only and use_llm_only:
        raise ValueError("Cannot set both use_ocr_only=True and use_llm_only=True simultaneously.")

    server_name_ocr = ""
    server_name_llm = ""

    # ========== OCR Recognition ==========
    if not use_llm_only:
        server_name_ocr_ret = ImageOcrRemote(image=image)()
        monitor_task_status_v2("OCR Raw Result", str(server_name_ocr_ret))

        if ocr_func is not None and callable(ocr_func):
            server_name_ocr = ocr_func(server_name_ocr_ret)
        elif ocr_index is not None:
            if isinstance(ocr_index, (list, tuple)) and len(ocr_index) == 2:
                server_name_ocr = server_name_ocr_ret[ocr_index[0]][ocr_index[1]]
            else:
                raise ValueError("ocr_index must be a tuple or list of length 2, e.g., (0, 0)")
        else:
            # Default: take the first recognition result; return empty string if none
            server_name_ocr = server_name_ocr_ret[0][0] if server_name_ocr_ret and server_name_ocr_ret[0] else ""

        server_name_ocr = str(server_name_ocr).strip()
        if ocr_fix_dict is not None:
            server_name_ocr = ocr_fix_dict.get(server_name_ocr, server_name_ocr)
        monitor_task_status_v2("OCR Result", server_name_ocr)

    # ========== LLM Recognition ==========
    if not use_ocr_only:
        _, img_url = image_upload(image=image)
        server_name_llm_ret = llm_call(img_url, user_prompt=user_prompt)
        server_name_llm = server_name_llm_ret.get(llm_key, "").strip()
        if llm_fix_dict is not None:
            server_name_llm = llm_fix_dict.get(server_name_llm, server_name_llm)
        monitor_task_status_v2("LLM Result", server_name_llm)

    # ========== Validation Logic ==========
    if not validation or use_ocr_only or use_llm_only:
        return server_name_ocr, server_name_llm

    if server_name_llm == server_name_ocr:
        return server_name_ocr, server_name_llm
    else:
        error_msg = f"OCR and LLM results are inconsistent | OCR: '{server_name_ocr}' | LLM: '{server_name_llm}'"
        monitor_task_status_v2("Validation Failed", error_msg)
        raise ValueError(error_msg)
